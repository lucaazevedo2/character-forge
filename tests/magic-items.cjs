const fs=require('fs'),vm=require('vm'),assert=require('assert');
const c=vm.createContext({itemData:()=>null,allItems:()=>[{name:'Dagger',cost:{quantity:2,unit:'gp'}},{name:'Potion of Healing',cost:{quantity:50,unit:'gp'}}],renderNav:()=>{},renderSheet:()=>{}});
for(const f of ['magic-items-data.js','magic-items.js','item-shop.js'])vm.runInContext(fs.readFileSync(''+f,'utf8'),c);
const run=s=>vm.runInContext(s,c);
assert(run('MAGIC_ITEMS.length')>900);
for(const r of ['Common','Uncommon','Rare','Very Rare','Legendary','Artifact'])assert(run(`MAGIC_ITEMS.some(x=>x.rarity===${JSON.stringify(r)})`));
assert.equal(run("allItems().filter(x=>x.name==='Potion of Healing').length"),1);
assert(run("allItems().some(x=>x.name==='Dagger')"));
assert(run("MAGIC_ITEMS.some(x=>x.setting==='Eberron')"));
run("const hero={gold:200,inventory:[]};const item={...MAGIC_ITEMS[0],cost:{quantity:1,unit:'gp'}};");
assert.equal(run('shopPrice(item)'),null);
assert(run('shopTransfer(hero,item,1,true).error'));
assert(run('shopCheckout(hero,[{item,quantity:1}],true).error'));
assert(run('shopCheckout(hero,[{item,quantity:1}],false).error'));
assert.equal(run('hero.gold'),200);assert.equal(run('hero.inventory.length'),0);
assert(run("shopCheckout(hero,[{item:{name:'Dagger',cost:{quantity:2,unit:'gp'}},quantity:1}],true).message"));
assert.equal(run('hero.gold'),198);
console.log('Magic catalog rarities/settings, duplicate suppression, no-price and cart protections passed.');
run('const potion=MAGIC_ITEMS.find(x=>x.index==="magic-potion-of-healing-common");const greater=MAGIC_ITEMS.find(x=>x.name==="Potion of Greater Healing");const shopper={gold:100,inventory:[]};');
assert.equal(run('shopPrice(potion)'),50);
assert.equal(run('shopPrice(greater)'),null);
assert.equal(run('shopPurchasableItems().filter(isMagicItem).length'),1);
assert(run('shopPurchasableItems().every(x=>shopPrice(x)!==null)'));
assert.equal(run('shopPurchasableItems().find(shopIsHealingPotion).cost.quantity'),50);
assert.equal(run('potion.cost'),undefined);
assert(run('shopCheckout(shopper,[{item:potion,quantity:2}],true).message'));
assert.equal(run('shopper.gold'),0);assert.equal(run('shopper.inventory.length'),2);
assert(run('shopCheckout(shopper,[{item:potion,quantity:1}],true).error'));
assert(run('shopCheckout(shopper,[{item:greater,quantity:1}],false).error'));
assert.equal(run('shopper.inventory.length'),2);
assert(!run('SHOP_CATEGORIES.some(([id])=>id==="magic")'));
console.log('PASS purchasable-only catalog, one standard 50-gp healing potion, no source mutation, purchase and higher-tier protections');
assert.equal(run('MAGIC_ITEMS.filter(x=>x.index.startsWith("magic-potion-of-healing-")).map(x=>x.name).join("|")'),'Potion of Healing|Potion of Greater Healing|Potion of Superior Healing|Potion of Supreme Healing');
assert.equal(run('itemData("Potion of Healing (Uncommon)").name'),'Potion of Greater Healing');
assert.equal(run('itemData("Potion of Healing (Rare)").name'),'Potion of Superior Healing');
assert.equal(run('itemData("Potion of Healing (Very Rare)").name'),'Potion of Supreme Healing');
run('const legacy={inventory:["Potion of Healing (Rare)","Potion of Healing (Rare)","Potion of Healing (Common)","Dagger"]};magicNormalizeHealingInventory(legacy);');
assert.equal(run('legacy.inventory.join("|")'),'Potion of Superior Healing|Potion of Superior Healing|Potion of Healing|Dagger');
assert.equal(run('magicNormalizeHealingInventory(legacy)'),false);
console.log('PASS healing potion names, legacy aliases, quantity-preserving inventory migration, and idempotence');
