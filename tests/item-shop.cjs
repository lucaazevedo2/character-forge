const fs=require('fs'),vm=require('vm'),assert=require('assert');
const context=vm.createContext({});vm.runInContext(fs.readFileSync('dist/item-shop.js','utf8'),context);
const run=code=>vm.runInContext(code,context);
assert.equal(run("shopCategory({name:'Longsword',weapon_category:'Martial'})"),'weapons');
assert.equal(run("shopCategory({name:'Shield',armor_class:{base:2}})"),'armor');
assert.equal(run("shopCategory({name:'Potion of healing'})"),'potions');
assert.equal(run("shopCategory({name:'Bag of Holding',rarity:{name:'Uncommon'}})"),'magic');
assert.equal(run("shopCategory({name:'Crossbow bolt',gear_category:{index:'ammunition'}})"),'ammunition');
assert.equal(run("shopCategory({name:'Disguise Kit',equipment_category:{index:'tools'}})"),'tools');
assert.equal(run("shopCategory({name:'Mule',equipment_category:{index:'mounts-and-vehicles'}})"),'travel');
assert.equal(run("shopCategory({name:'Backpack'})"),'gear');
run("const c={gold:5,inventory:[]};const dagger={name:'Dagger',cost:{quantity:2,unit:'gp'}};");
assert.equal(run("shopTransfer(c,dagger,3,true).error"),'Not enough gold for this purchase.');
assert.equal(run('c.inventory.length'),0);assert.equal(run('c.gold'),5);
run('shopTransfer(c,dagger,2,true)');assert.equal(run('c.gold'),1);assert.equal(run('c.inventory.length'),2);
run('shopTransfer(c,dagger,3,false)');assert.equal(run('c.gold'),1);assert.equal(run('c.inventory.length'),5);
assert.ok(run('shopTransfer(c,dagger,0,false).error'));assert.ok(run('shopTransfer(c,dagger,1.5,false).error'));
assert.ok(run("shopTransfer(c,{name:'Unpriced'},1,true).error"));
assert.equal(run("shopPrice({cost:{quantity:5,unit:'sp'}})"),.5);
const html=fs.readFileSync('dist/index.html','utf8');assert(!html.includes('id="itemCatalog"'));assert(html.includes('id="customItemName"'));assert(html.includes('id="addOther"'));assert(html.includes('<script src="item-shop.js"></script>'));
console.log('PASS shop categories, currency, quantity, purchase limits, free additions, and custom item controls');

run("const shopper={gold:10,inventory:[]};const order=[{item:{name:'Arrow',cost:{quantity:5,unit:'cp'}},quantity:3},{item:dagger,quantity:2}];");
assert.equal(run('shopCartSummary(shopper,order).total'),4.15);
assert.equal(run('shopCartSummary(shopper,order).remaining'),5.85);
assert.equal(run('shopCartSummary(shopper,order).affordable'),true);
assert.ok(run('shopCheckout(shopper,order,true).message'));assert.equal(run('shopWalletCopper(shopWallet(shopper))/100'),5.85);assert.equal(run('shopper.inventory.length'),5);
run('shopper.gold=1;shopper.coins={}');assert.equal(run('shopCartSummary(shopper,order).affordable'),false);
assert.ok(run('shopCheckout(shopper,order,true).error'));assert.equal(run('shopper.gold'),1);assert.equal(run('shopper.inventory.length'),5);
assert.ok(run('shopCheckout(shopper,order,false).message'));assert.equal(run('shopper.gold'),1);assert.equal(run('shopper.inventory.length'),10);
assert.ok(run('shopCheckout(shopper,[],true).error'));
assert.ok(run("shopCheckout(shopper,[{item:{name:'Mystery item'},quantity:1}],true).error"));
run('shopper.gold=4.15;shopper.coins={}');assert.equal(run('shopCartSummary(shopper,order).remaining'),0);assert.ok(run('shopCheckout(shopper,order,true).message'));assert.equal(run('shopper.gold'),0);
console.log('PASS cart totals, exact balance, atomic checkout, insufficient funds, unpriced items, and free cart additions');

assert.equal(run("shopWalletCopper(shopWallet({gold:1,coins:{cp:3,sp:2,ep:1,pp:1}}))"),1173);
assert.equal(run("shopWalletCopper(shopWallet({gold:12.34}))"),1234);
assert.equal(run("shopWallet({gold:12.34}).gp"),12);
assert.equal(run("shopWallet({gold:12.34}).sp"),3);
assert.equal(run("shopWallet({gold:12.34}).cp"),4);
assert.equal(run("shopWalletCopper(shopSpendWallet({cp:0,sp:0,ep:0,gp:0,pp:1},215))"),785);
assert.equal(run("shopSpendWallet({cp:0,sp:0,ep:0,gp:0,pp:1},215).gp"),7);
assert.equal(run("shopSpendWallet({cp:0,sp:0,ep:0,gp:0,pp:1},215).sp"),8);
assert.equal(run("shopSpendWallet({cp:0,sp:0,ep:0,gp:0,pp:1},215).cp"),5);
assert.equal(run("shopSpendWallet({cp:0,sp:0,ep:1,gp:0,pp:0},51)"),null);
assert.equal(run("shopWalletCopper(shopSpendWallet({cp:2,sp:3,ep:2,gp:1,pp:1},117))"),1115);
